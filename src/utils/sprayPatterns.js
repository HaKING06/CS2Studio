/**
 * Retrieve weapon metadata and spray pattern by weapon ID (supports common CS2 aliases).
 * @param {string} id
 * @returns {object|null}
 */
export function getWeaponData(id) {
  if (!id) return null;
  const key = String(id).trim().toLowerCase();
  const resolved = WEAPON_ALIASES[key] || key;
  return SPRAY_WEAPONS[resolved] || null;
}

/**
 * Compute scaled cumulative wall coordinates (+X right, +Y up) for a weapon pattern.
 * @param {string} id
 * @param {number} [scale=1]
 * @returns {Array<{shot: number, x: number, y: number, cumX: number, cumY: number, bulletDx: number, bulletDy: number, delayMs: number}>}
 */
export function getCumulativeWallPoints(id, scale = 1) {
  const weapon = getWeaponData(id);
  if (!weapon) return [];
  const factor = Number.isFinite(scale) ? scale : 1;
  return weapon.pattern.map((step) => ({
    shot: step.shot,
    x: step.cumX * factor,
    y: step.cumY * factor,
    cumX: step.cumX * factor,
    cumY: step.cumY * factor,
    bulletDx: step.bulletDx * factor,
    bulletDy: step.bulletDy * factor,
    delayMs: step.delayMs,
  }));
}
